"""--completion bash|zsh|fish: shell completion scripts (#16).

Generated from the argparse parsers themselves (main options and
`untis init`), so they never fall behind the real flags. No extra
dependency: each shell gets a small script built from Option records.

    untis --completion zsh  > ~/.zfunc/_untis
    untis --completion bash > ~/.local/share/bash-completion/completions/untis
    untis --completion fish > ~/.config/fish/completions/untis.fish
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass, field

SHELLS = ("bash", "zsh", "fish")
# Options whose value is a file or a directory.
FILE_DESTS = {"config", "env"}
DIR_DESTS = {"dir"}


@dataclass
class Option:
    flags: list[str]                     # e.g. ["-s", "--short"]
    help: str = ""
    takes_value: bool = False
    optional_value: bool = False         # nargs="?" (e.g. --json [-])
    choices: list[str] = field(default_factory=list)
    kind: str = ""                       # "file" / "dir" / "" for the value

    @property
    def long(self) -> list[str]:
        return [f[2:] for f in self.flags if f.startswith("--")]

    @property
    def short(self) -> list[str]:
        return [f[1:] for f in self.flags if len(f) == 2 and f[0] == "-" and f[1] != "-"]


def short_help(text: str | None, limit: int = 70) -> str:
    """The first sentence of an argparse help text, on one line and at
    most `limit` characters ("" for SUPPRESS / none)."""
    if not text or text == argparse.SUPPRESS:
        return ""
    text = " ".join(text.split())
    # "(default: /home/…/config.json)" would put local paths into the script.
    text = re.sub(r"\s*\(default[^)]*\)", "", text)
    # A sentence ends at ". " before a capital letter (not at "e.g. untis").
    first = re.split(r"(?<=[.!?])\s(?=[A-Z])", text, maxsplit=1)[0].rstrip(".")
    return first if len(first) <= limit else first[: limit - 1].rstrip() + "…"


def options(parser: argparse.ArgumentParser) -> list[Option]:
    """The parser's options (positionals and --help excluded)."""
    out = []
    for a in parser._actions:
        if not a.option_strings or isinstance(a, argparse._HelpAction):
            continue
        takes = a.nargs != 0 and not isinstance(
            a, (argparse._StoreConstAction, argparse._VersionAction,
                argparse.BooleanOptionalAction, argparse._StoreTrueAction))
        kind = "file" if a.dest in FILE_DESTS else "dir" if a.dest in DIR_DESTS else ""
        out.append(Option(
            flags=list(a.option_strings), help=short_help(a.help), takes_value=takes,
            optional_value=takes and a.nargs == "?",
            choices=[str(c) for c in a.choices] if a.choices else [], kind=kind))
    return out


# --- bash ---------------------------------------------------------------------
def _bash_value_cases(opts: list[Option]) -> list[str]:
    lines = []
    for o in opts:
        if not o.takes_value or o.optional_value and not o.choices:
            continue
        pattern = "|".join(o.flags)
        if o.choices:
            action = f'COMPREPLY=($(compgen -W "{" ".join(o.choices)}" -- "$cur")); return 0;;'
        elif o.kind == "file":
            action = 'COMPREPLY=($(compgen -f -- "$cur")); return 0;;'
        elif o.kind == "dir":
            action = 'COMPREPLY=($(compgen -d -- "$cur")); return 0;;'
        else:
            action = "return 0;;"            # a free value (number, day, …)
        lines.append(f"        {pattern}) {action}")
    return lines


def bash_script(main: list[Option], init: list[Option]) -> str:
    main_words = " ".join(f for o in main for f in o.flags)
    init_words = " ".join(f for o in init for f in o.flags)
    return "\n".join([
        "# bash completion for untis (generated by `untis --completion bash`)",
        "_untis() {",
        '    local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"',
        "    COMPREPLY=()",
        '    if [[ "${COMP_WORDS[1]}" == init && $COMP_CWORD -gt 1 ]]; then',
        '        case "$prev" in',
        *_bash_value_cases(init),
        "        esac",
        f'        COMPREPLY=($(compgen -W "{init_words} --help" -- "$cur"))',
        "        return 0",
        "    fi",
        '    case "$prev" in',
        *_bash_value_cases(main),
        "    esac",
        '    if [[ $COMP_CWORD -eq 1 && "$cur" != -* ]]; then',
        '        COMPREPLY=($(compgen -W "init" -- "$cur"))',
        "        return 0",
        "    fi",
        f'    COMPREPLY=($(compgen -W "{main_words} --help" -- "$cur"))',
        "}",
        "complete -F _untis untis",
        "",
    ])


# --- zsh ------------------------------------------------------------------------
def _zsh_escape(text: str) -> str:
    """For an _arguments description: no [ ] : ' and backslashes."""
    return (text.replace("\\", "").replace("'", "").replace("[", "(").replace("]", ")")
            .replace(":", " -"))


def _zsh_spec(o: Option) -> str:
    desc = f"[{_zsh_escape(o.help)}]" if o.help else ""
    value = ""
    if o.takes_value:
        name = "value"
        if o.choices:
            action = "(" + " ".join(o.choices) + ")"
        elif o.kind == "file":
            action = "_files"
        elif o.kind == "dir":
            action = "_files -/"
        else:
            action = " "
        value = (":" if o.optional_value else "") + f":{name}:{action}"
    if len(o.flags) == 1:
        return f"'{o.flags[0]}{desc}{value}'"
    group = " ".join(o.flags)
    return f"'({group})'{{{','.join(o.flags)}}}'{desc}{value}'"


def zsh_script(main: list[Option], init: list[Option]) -> str:
    main_specs = " \\\n        ".join(_zsh_spec(o) for o in main)
    init_specs = " \\\n            ".join(_zsh_spec(o) for o in init)
    return "\n".join([
        "#compdef untis",
        "# zsh completion for untis (generated by `untis --completion zsh`)",
        "_untis() {",
        "    if (( CURRENT > 2 )) && [[ ${words[2]} == init ]]; then",
        "        _arguments -s \\",
        f"            {init_specs}",
        "        return",
        "    fi",
        "    _arguments -s \\",
        f"        {main_specs} \\",
        "        '1:: :(init)'",
        "}",
        '_untis "$@"',
        "",
    ])


# --- fish -----------------------------------------------------------------------
def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _fish_line(o: Option, condition: str) -> str:
    parts = ["complete -c untis", f"-n {_fish_quote(condition)}"]
    parts += [f"-s {s}" for s in o.short] + [f"-l {l}" for l in o.long]
    if o.takes_value:
        if o.choices:
            parts.append(f"-x -a {_fish_quote(' '.join(o.choices))}")
        elif o.kind in ("file", "dir"):
            parts.append("-r -F" if o.kind == "file" else f"-x -a {_fish_quote('(__fish_complete_directories)')}")
        else:
            parts.append("-x")
    if o.help:
        parts.append(f"-d {_fish_quote(o.help)}")
    return " ".join(parts)


def fish_script(main: list[Option], init: list[Option]) -> str:
    lines = ["# fish completion for untis (generated by `untis --completion fish`)",
             "complete -c untis -f",
             "complete -c untis -n '__fish_use_subcommand' -a init "
             "-d 'Set up config.json and .env'"]
    lines += [_fish_line(o, "not __fish_seen_subcommand_from init") for o in main]
    lines += [_fish_line(o, "__fish_seen_subcommand_from init") for o in init]
    return "\n".join(lines) + "\n"


def script(shell: str, main_parser: argparse.ArgumentParser,
           init_parser: argparse.ArgumentParser) -> str:
    """The completion script for `shell` (bash, zsh or fish)."""
    builders = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}
    if shell not in builders:
        raise ValueError(f"unknown shell {shell!r} (use {', '.join(SHELLS)})")
    return builders[shell](options(main_parser), options(init_parser))

